local root=...;local C=dofile(root..'Scripts/config.lua');local lib=dofile(root..'Scripts/scheduler.lua')
local manifest=dofile(root..'Scripts/manifest.lua')
local seq,plays,states,volumes=0,{},{},{}
local B={play=function(file,volume)seq=seq+1;plays[#plays+1]=file;volumes[#volumes+1]=volume;return seq end,poll=function(id)return states[id]end,stop=function()seq=seq+1;return seq end}
local function random(n)return n and 1 or 0 end
local s=lib.new(C,manifest,B,random)
assert(s:offer('combat',0,0,2));s:tick(0);assert(#plays==1)
s:offer('playerwounded',0.1,0,2);s:tick(.2);assert(#plays==1,'overlap')
-- Duration estimates do not release the lock; only real completion does.
s:tick(10);assert(#plays==1 and s.flight,'duration incorrectly unlocked')
states[1]='done';s:tick(11);assert(not s.flight and #plays==1,'stale line played')
s:offer('playerreload',12,0,2);s:tick(12);assert(#plays==2)
states[2]='done';s:tick(13)
s:offer('playerreload',14,0,2);s:tick(14);assert(#plays==2,'cooldown ignored')
s:offer('combat',20,0,2);s:offer('playerwounded',20,0,2);s:tick(20);assert(plays[3]:find('playerwounded'),'priority wrong')
states[3]='done';s:tick(21)
s:offer('replytoenemy',22,.35,2);s:tick(22.2);assert(#plays==3);s:tick(22.4);assert(#plays==4)
states[4]='done';s:tick(23);s:offer('replytoenemy',40,0,2);s:tick(40);assert(plays[4]~=plays[5],'immediate repeat')
s:clear(41);local cancel=s.flight.id;s:offer('combat',42,0,2);s:tick(42);assert(#plays==5,'stop did not hold channel')
states[cancel]='stopped';s:tick(43);s:tick(43.5);assert(#plays==6)
s:tick(80);assert(not s.enabled and s.stats.failed==1,'host timeout not fail closed')
s:clear(81);assert(s.enabled and s.flight,'travel/reconnect must recover behind a stop acknowledgement')
states[s.flight.id]='stopped';s:tick(82);C.volume=0.34;s:offer('playerreload',83,0,2,true);s:tick(83);assert(volumes[#volumes]==0.34,'changed slider volume not passed to playback')
local g=lib.new(C,manifest,B,random)
g:offer('combat',100,0,1,true);g:tick(100)
g:offer('grenadeout',100.1,0,4,true);g:tick(102);assert(g.pending and g.pending.category=='grenadeout','grenade expired before ongoing speech completed')
states[g.flight.id]='done';g:tick(102.5);g:tick(103);assert(plays[#plays]:find('grenadeout'),'queued grenade failed after completion')
local count=0;for _,list in pairs(manifest)do for _,v in ipairs(list)do assert(v.duration>0 and v.duration<15);count=count+1 end end;assert(count==152)
print('PASS: no overlap, actual completion, stale expiry, cooldown, priority, reply delay, repeat avoidance, cancel, host failure, 152 clips')
